# GreenDeer first-run helper: create local.env interactively.
# Called by start.bat when local.env does not exist. Git-ignored file.
param([string]$Password)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root 'local.env'

if (Test-Path $envFile) {
  Write-Output 'local.env already exists - nothing to do.'
  exit 0
}

if (-not $Password) {
  Write-Host ''
  Write-Host 'GreenDeer first run needs the MySQL password to connect.'
  Write-Host 'It will be stored in local.env (plain text, git-ignored, never committed).'
  $p1 = Read-Host 'Enter MySQL DB_PASSWORD'
  $p2 = Read-Host 'Confirm   MySQL DB_PASSWORD'
  if ($p1 -cne $p2) {
    Write-Error 'Passwords do not match - rerun start.bat.'
    exit 1
  }
  $Password = $p1
}

$lines = @(
  '# GreenDeer local DB credentials - generated by start.bat / ensure-local-env.ps1.',
  '# git-ignored, never committed.',
  'DB_HOST=127.0.0.1',
  'DB_PORT=3306',
  'DB_NAME=greendeer',
  'DB_USER=root',
  ('DB_PASSWORD=' + $Password)
)
Set-Content -Encoding Ascii -Path $envFile -Value $lines
Write-Output ('local.env created: ' + $envFile)
exit 0
